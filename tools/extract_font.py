#!/usr/bin/env python3
"""Converts tools/data/font.inl (TIC-80's built-in font, MIT, from the TIC-80 repo) to
src/game/font.odin (generated; do not hand-edit). One byte per glyph row, bit 0 = leftmost pixel."""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
b = [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]{2}', open(os.path.join(ROOT, 'tools/data/font.inl')).read())]
b += [0] * (1024 - len(b))
rows = ["// Generated by tools/extract_font.py from tools/data/font.inl (TIC-80 font, MIT). Do not hand-edit.",
        "package game\n", "FONT := [128][8]u8{"]
for g in range(128):
    rows.append("\t{" + ", ".join(f"0x{v:02x}" for v in b[g*8:g*8+8]) + "},")
rows.append("}\n")
open(os.path.join(ROOT, 'src/game/font.odin'), 'w').write("\n".join(rows))
