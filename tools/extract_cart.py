#!/usr/bin/env python3
"""Reads pyramid.tic and writes src/game/assets.odin (generated; do not hand-edit).

Chunk layout: [type(low 5 bits)|bank(high 3 bits)][size u16 LE][reserved][data].
Types (TIC-80 1.1): 1 tiles, 2 sprites, 4 map, 5 code, 6 flags, 9 samples,
10 waveforms, 12 palette, 14 music tracks, 15 patterns, 18 cover screen.
Chunks are stored trimmed of trailing zeros, so pad to full size.
Usage: python3 -I tools/extract_cart.py [cart] [out.odin] [--dump DIR]
"""
import sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZES = {1: 8192, 2: 8192, 4: 32640, 6: 512, 12: 48, 9: 4224, 14: 408, 15: 11520, 18: 16320}

def chunks(path):
    d = open(path, 'rb').read()
    i, out = 0, {}
    while i + 4 <= len(d):
        t, bank = d[i] & 31, d[i] >> 5
        n = d[i+1] | d[i+2] << 8
        out[(t, bank)] = d[i+4:i+4+n]
        i += 4 + n
    return out

def padded(c, t):
    b = bytearray(c.get((t, 0), b''))
    b += bytes(SIZES[t] - len(b))
    return bytes(b)

def unpack4(b):  # TIC-80 4bpp: even pixel in the low nibble
    return [v for x in b for v in (x & 15, x >> 4)]

def odin_array(name, typ, vals, per=32):
    lines = [f"{name} := [{len(vals)}]{typ}{{"]
    for i in range(0, len(vals), per):
        lines.append("\t" + ", ".join(str(v) for v in vals[i:i+per]) + ",")
    lines.append("}\n")
    return "\n".join(lines)

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    cart = args[0] if args else os.path.join(ROOT, 'pyramid.tic')
    out = args[1] if len(args) > 1 else os.path.join(ROOT, 'src/game/assets.odin')
    c = chunks(cart)
    if '--dump' in sys.argv:
        d = sys.argv[sys.argv.index('--dump') + 1]
        os.makedirs(d, exist_ok=True)
        for (t, bank), data in c.items():
            open(os.path.join(d, f"chunk{t}_{bank}.bin"), 'wb').write(data)
    pal = padded(c, 12)
    palette = [pal[i] << 16 | pal[i+1] << 8 | pal[i+2] for i in range(0, 48, 3)]
    m = bytearray(padded(c, 4))
    for i, t in enumerate(m):  # BOOT: tiles 32..63 become t-32
        if 32 <= t < 64:
            m[i] = t - 32
    s = ["// Generated by tools/extract_cart.py from pyramid.tic. Do not hand-edit.", "package game\n",
         "MAP_W :: 240", "MAP_H :: 136\n",
         "// 0xRRGGBB", odin_array("PALETTE", "u32", [f"0x{p:06X}" for p in palette], 8),
         "// 256 background tiles then 256 sprites, 8x8 pixels of palette indices",
         odin_array("TILES", "u8", unpack4(padded(c, 1)), 64),
         odin_array("SPRITES", "u8", unpack4(padded(c, 2)), 64),
         "// Sprite flags (fget): bit 7 solid, bit 6 door",
         odin_array("FLAGS", "u8", list(padded(c, 6)), 32),
         "// Map after BOOT's tile 32..63 -> t-32 transform, row-major MAP_W x MAP_H",
         odin_array("MAP_INITIAL", "u8", list(m), 60)]
    open(out, 'w').write("\n".join(s))
    print("wrote", out, {k: len(v) for k, v in sorted(c.items())})

main()
