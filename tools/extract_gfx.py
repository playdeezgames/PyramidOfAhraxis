#!/usr/bin/env python3
"""Picks the game's pictures out of the Urizen 1-bit tileset (CC0, by vurmux) and packs the DINOBYTE
font (CC BY 4.0, by mby) into generated Odin: src/game/gfx.odin and src/game/font.odin (do not
hand-edit). Run: python3 -I tools/extract_gfx.py

Urizen tiles are 12x12 with a 1px gap (tile (col,row) starts at 13*col+1, 13*row+1), one colour per
tile on black. Each picture is taken as a mask and painted in one Sweetie-16 palette index."""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sheet = Image.open(os.path.join(ROOT, 'tools/data/urizen_onebit_tileset__v2d0.png')).convert('RGB')

# name -> (col, row, palette index). Order is the Gfx enum order in src/game/render.odin.
PICKS = [
    ('Wall',        0, 2, 13),   # grey cobblestone
    ('Door',        4, 1, 4),    # orange door with a knob
    ('Door_Window', 5, 1, 4),    # same with a small window
    ('Exit',       24, 0, 11),   # stairs up
    ('Trap',        3, 25, 2),   # red spikes/blood, shown once sprung
    ('Key',        28, 23, 4),
    ('Potion',     30, 4, 2),    # red flask
    ('Jool',        1, 22, 11),  # cyan gem
    ('Shield',     26, 12, 9),
    ('Sword',      39, 6, 12),
    ('Monster',   104, 6, 3),    # devil
    ('Player',    104, 0, 12),   # plain white person
    ('Dead',      104, 10, 13),  # skeleton
    ('Heart',      78, 37, 2),
    ('Heart_Empty', 78, 37, 14),  # the same heart, darkened, for missing health
    # Per-dungeon looks (a theme recolours these) and the light sources.
    ('Wall_Brick',  0, 3, 2),    # red brick
    ('Wall_Block',  7, 0, 4),    # framed sandstone block
    ('Wall_Wood',   0, 4, 3),    # planks
    ('Wall_Round', 22, 2, 10),   # dark brick with rounded corners
    ('Floor_Dots',  2, 5, 15),   # dotted columns
    ('Floor_Hatch', 3, 5, 15),   # diagonal hatch
    ('Floor_Weave', 8, 5, 15),   # herringbone
    ('Floor_Cross', 0, 6, 1),    # carpet crosses
    ('Floor_Moss', 19, 6, 6),    # mossy ground
    ('Candle',     30, 22, 12),  # a torch pickup
    ('Lantern',    26, 22, 4),
    ('Brazier',    28, 22, 3),   # a fixed light, solid
    ('Merchant',  106, 0, 4),    # the jool shop
    ('Wraith',    104, 7, 11),   # a hunter
    ('Kit',        29, 25, 12),  # disarm kit
]

def tile(col, row, color):
    t = sheet.crop((13 * col + 1, 13 * row + 1, 13 * col + 13, 13 * row + 13))
    return [color if max(t.getpixel((x, y))) > 0 else 0 for y in range(12) for x in range(12)]

out = ["// Generated by tools/extract_gfx.py from tools/data/urizen_onebit_tileset__v2d0.png. Do not hand-edit.",
       "// Urizen 1-bit tileset by vurmux, https://vurmux.itch.io/urizen-onebit-tileset, CC0 1.0.",
       "package game", "", f"GFX_COUNT :: {len(PICKS)}", "", "// 12x12 palette indices per picture (0 = background).",
       f"GFX := [{len(PICKS)}][144]u8{{"]
for name, c, r, color in PICKS:
    px = tile(c, r, color)
    assert any(px), name
    out.append(f"\t// {name} ({c}, {r})")
    out.append("\t{" + ", ".join(str(v) for v in px) + "},")
out.append("}\n")
open(os.path.join(ROOT, 'src/game/gfx.odin'), 'w').write("\n".join(out))

font = Image.open(os.path.join(ROOT, 'tools/data/dbyte_1x.png')).convert('RGBA')
assert font.size == (96, 128), font.size
glyphs = []
for code in range(256):
    cx, cy = (code % 16) * 6, (code // 16) * 8
    bits = 0
    for y in range(8):
        for x in range(6):
            if font.getpixel((cx + x, cy + y))[3] > 0:
                bits |= 1 << (y * 6 + x)
    glyphs.append(bits)
lines = ["// Generated by tools/extract_gfx.py from tools/data/dbyte_1x.png (unmodified). Do not hand-edit.",
         "// DINOBYTE bitmap font by mby, https://mby.itch.io/dinobyte, CC BY 4.0.",
         "package game", "", "// 6x8 glyphs, one u64 per code page 437 character; bit (row*6 + col) is lit.",
         "FONT := [256]u64{"]
for i in range(0, 256, 4):
    lines.append("\t" + " ".join("0x%012X," % v for v in glyphs[i:i + 4]))
lines.append("}\n")
open(os.path.join(ROOT, 'src/game/font.odin'), 'w').write("\n".join(lines))
